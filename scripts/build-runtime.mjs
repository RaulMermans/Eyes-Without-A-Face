#!/usr/bin/env node
/**
 * Bundle the portable mapping runtime (src/export/runtime/runtime.ts) into one
 * dependency-free ES module that every export package ships unchanged.
 *
 *   node scripts/build-runtime.mjs            write src/export/runtime/generated/eyes-mapping-runtime.mjs
 *   node scripts/build-runtime.mjs --check    fail if the committed bundle is stale
 *   node scripts/build-runtime.mjs --out DIR  write the bundle into DIR (used by the freshness test)
 *
 * The bundle is committed so that the code inside an exported package is
 * reviewable in the repository and identical to what the app hashes.
 */
import { mkdtempSync, readFileSync, rmSync, writeFileSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const entry = path.join(root, "src/export/runtime/runtime.ts");
const committed = path.join(root, "src/export/runtime/generated/eyes-mapping-runtime.mjs");
const committedNotices = path.join(root, "src/export/runtime/generated/THIRD_PARTY_NOTICES.md");
const HEADER =
  "// eyes-mapping-runtime — GENERATED by scripts/build-runtime.mjs from src/export/runtime/runtime.ts. Do not edit.\n" +
  "// Bundles the app's deterministic mapping engine, contract validator and acceptance-policy classifier (Apache-2.0).\n";

export async function bundleRuntime() {
  const outDir = mkdtempSync(path.join(tmpdir(), "eyes-runtime-"));
  try {
    await build({
      configFile: false,
      root,
      logLevel: "silent",
      build: {
        outDir,
        emptyOutDir: true,
        minify: false,
        sourcemap: false,
        target: "es2023",
        reportCompressedSize: false,
        copyPublicDir: false,
        lib: { entry, formats: ["es"], fileName: () => "eyes-mapping-runtime.mjs" },
      },
    });
    return HEADER + readFileSync(path.join(outDir, "eyes-mapping-runtime.mjs"), "utf8");
  } finally {
    rmSync(outDir, { recursive: true, force: true });
  }
}

/** License texts of every third-party package rolled into the bundle, read from the package itself. */
export function thirdPartyNotices(bundle) {
  const dirs = [...new Set([...bundle.matchAll(/node_modules\/\.pnpm\/([^/\s]+)\/node_modules\/((?:@[^/\s]+\/)?[^/\s]+)\//g)].map((m) => `${m[1]}/node_modules/${m[2]}`))].sort();
  const sections = dirs.map((dir) => {
    const base = path.join(root, "node_modules/.pnpm", dir);
    const pkg = JSON.parse(readFileSync(path.join(base, "package.json"), "utf8"));
    const license = readFileSync(path.join(base, "LICENSE"), "utf8").trim();
    return `## ${pkg.name} ${pkg.version} (${pkg.license})\n\n\`\`\`text\n${license}\n\`\`\`\n`;
  });
  return `# Third-party notices\n\nThe runtime \`runtime/eyes-mapping-runtime.mjs\` bundles these packages unchanged.\n\n${sections.join("\n")}`;
}

async function main() {
  const args = process.argv.slice(2);
  const source = await bundleRuntime();
  if (args.includes("--check")) {
    const current = readFileSync(committed, "utf8");
    if (current !== source || readFileSync(committedNotices, "utf8") !== thirdPartyNotices(source)) {
      console.error("eyes-mapping-runtime.mjs is stale. Run: node scripts/build-runtime.mjs");
      process.exit(1);
    }
    console.log("eyes-mapping-runtime.mjs is up to date.");
    return;
  }
  const outIndex = args.indexOf("--out");
  const target = outIndex >= 0 ? path.join(path.resolve(args[outIndex + 1]), "eyes-mapping-runtime.mjs") : committed;
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, source);
  writeFileSync(path.join(path.dirname(target), "THIRD_PARTY_NOTICES.md"), thirdPartyNotices(source));
  console.log(`Wrote ${path.relative(root, target)} (${Buffer.byteLength(source)} bytes)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
